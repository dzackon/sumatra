(* ================================================================= *)
(* Substitution commutations for β-redexes                           *)
(* ================================================================= *)
(** [asimpl] does not simplify these forms automatically, so we prove
    them once from the generated composition lemmas. *)

Section SubstExtra.

  (* e[↑σ][v..] = e[v .: σ] *)
  Lemma subst_scons_decompose {m n} (σ : fin m -> tm n) (e : tm (S m)) (v : tm n) :
    subst_tm (scons v tm_var) (subst_tm (up_tm_tm σ) e) = subst_tm (scons v σ) e.
  Proof.
    rewrite compComp_tm. apply ext_tm. intros [x|]; cbn.
    - unfold funcomp. rewrite renComp_tm. now apply idSubst_tm.
    - reflexivity.
  Qed.

  (* e[v..][f] = e[↑f][v[f]..] *)
  Lemma subst_beta_comm {m n} (f : fin m -> tm n) (e : tm (S m)) (v : tm m) :
    subst_tm f (subst_tm (scons v tm_var) e) =
    subst_tm (scons (subst_tm f v) tm_var) (subst_tm (up_tm_tm f) e).
  Proof.
    rewrite subst_scons_decompose, compComp_tm.
    apply ext_tm. intros [x|]; reflexivity.
  Qed.

  (* e[↑σ][v .: (ξ >> var)] = e[v .: (σ >> ⟨ξ⟩)] *)
  Lemma subst_scons_ren_decompose {m n k}
        (σ : fin m -> tm n) (xi : fin n -> fin k) (v : tm k) (e : tm (S m)) :
    subst_tm (scons v (funcomp tm_var xi)) (subst_tm (up_tm_tm σ) e)
    = subst_tm (scons v (funcomp (ren_tm xi) σ)) e.
  Proof.
    rewrite compComp_tm. apply ext_tm. intros [x|]; cbn.
    - unfold funcomp. rewrite renComp_tm.
      symmetry. apply rinst_inst_tm. reflexivity.
    - reflexivity.
  Qed.

End SubstExtra.
