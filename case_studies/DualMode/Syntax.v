Fixpoint ren_tm {m n : nat} (xi : fin m -> fin n) (s : tm m) : tm n :=
    match s return tm n with
    | tm_var _ s        => (tm_var n) (xi s)
    | tm_lam _ s0 s1    => tm_lam n s0 ((ren_tm (upRen_tm_tm xi)) s1)
    | tm_app _ s0 s1    => tm_app n ((ren_tm xi) s0) ((ren_tm xi) s1)
    | tm_box _ s0       => tm_box n ((ren_tm xi) s0)
    | tm_letbox _ s0 s1 => tm_letbox n ((ren_tm xi) s0) ((ren_tm (upRen_tm_tm xi)) s1)
    end.

Definition up_tm_tm {m n : nat} (sigma : fin m -> tm n) : fin (S m) -> tm (S n) :=
