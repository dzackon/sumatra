Section ty.
Inductive ty : Type :=
  | ty_base  : ty             (* base type *)
  | ty_arrow : ty -> ty -> ty (* A ⇒ B (A ⊃ B / A ⊸ B) *)
  | ty_box : ty -> ty.        (* □ A   (□ A / !A, source higher mode, used at lower) *)

Lemma congr_base : ty_base  = ty_base.
Proof. congruence. Qed.

Lemma congr_arrow {s0 s1 t0 t1 : ty} (H1 : s0 = t0) (H2 : s1 = t1) :
  ty_arrow s0 s1 = ty_arrow t0 t1.
Proof. congruence. Qed.

Lemma congr_box {s0 t0 : ty} (H1 : s0 = t0) : ty_box s0 = ty_box t0.
Proof. congruence. Qed.

End ty.

